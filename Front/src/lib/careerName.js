// Номи ихтисос барои нишон додан: рамзҳои дохилии база дар қавс
// («(ФМДМТбоДДБ)», «(FMTDMTBvaDTT)») ба хонанда маъное надоранд — пинҳон.
// Қавсҳои маънидор («(графикӣ)», «(интерйер)») мемонанд: дар онҳо 3 ҳарфи калони пайдарпай нест.
const CODE_IN_PARENS = /\s*\((?=[^)]*[A-ZА-ЯЁҶҲҚҒӮӢ]{3})[A-Za-zА-Яа-яЁёҶҷҲҳҚқҒғӮӯӢӣ]{5,}\)/g;

export const displayName = (name) => String(name || "").replace(CODE_IN_PARENS, "").trim();
