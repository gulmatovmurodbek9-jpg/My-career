// Ҳар changeLanguage аввал файли забонро бор мекунад (дар ҳамаи ҷойҳои сайт ҳамин кор мекунад).
const originalChange = i18n.changeLanguage.bind(i18n);
i18n.changeLanguage = async (lng, callback) => {
    await loadLanguage(lng).catch(() => { });
    return originalChange(lng, callback);
};

// Забони нигоҳдошташуда пеш аз нишон додани сайт бор мешавад (main.jsx интизор мешавад).
export const i18nReady = activeLang === 'tj' ? Promise.resolve() : i18n.changeLanguage(activeLang).catch(() => { });

// 41: <html lang> бо забони интихобшуда (тоҷикӣ — «tg» аз рӯи ISO 639-1).
const setHtmlLang = (lng) => {
    if (typeof document !== 'undefined') document.documentElement.lang = lng === 'tj' ? 'tg' : lng;
};
setHtmlLang(i18n.language);
i18n.on('languageChanged', setHtmlLang);

