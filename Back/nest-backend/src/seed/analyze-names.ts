function familyOf(name: string): string {
    const lower = name.toLowerCase();
    for (const [probe, label] of PROBES) {
        if (lower.includes(probe)) return label;
    }
    return '— номаълум —';
}

function main(): void {
    const clusterFilter = process.argv[2] ? Number(process.argv[2]) : null;
    const data = parseNtcData();

    const careers = clusterFilter
        ? data.careers.filter((c) => c.clusterNumber === clusterFilter)
        : data.careers;

    const groups = new Map<string, string[]>();
    for (const career of careers) {
        const family = familyOf(career.name);
        groups.set(family, [...(groups.get(family) ?? []), career.name]);
    }

    const sorted = [...groups.entries()].sort((a, b) => b[1].length - a[1].length);
    console.log(`${careers.length} ихтисос${clusterFilter ? ` (кластери ${clusterFilter})` : ''} → ${sorted.length} оила\n`);
    for (const [family, names] of sorted) {
        console.log(`${String(names.length).padStart(4)}  ${family}`);
    }

    const unknown = groups.get('— номаълум —') ?? [];
    if (unknown.length) {
        console.log(`\nБе оила (${unknown.length}):`);
        [...new Set(unknown)].forEach((name) => console.log('   ', name));
    }
}

main();
