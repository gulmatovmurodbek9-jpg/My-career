/** Falls back to the cluster's broadest family when no keyword matches. */
const CLUSTER_FALLBACK: Record<number, keyof typeof FAMILIES> = {
    1: 'mechanical',
    2: 'economics',
    3: 'teaching',
    4: 'law',
    5: 'medicine',
};

/** The family key a name matches, or null when no probe fires. */
export function matchFamilyKey(name: string): keyof typeof FAMILIES | null {
    const lower = name.toLowerCase();
    for (const [probe, key] of PROBES) {
        if (lower.includes(probe)) return key;
    }
    return null;
}

export function resolveFamily(name: string, clusterNumber: number): Family {
    const matched = matchFamilyKey(name);
    if (matched) return FAMILIES[matched];
    return FAMILIES[CLUSTER_FALLBACK[clusterNumber] ?? 'mechanical'];
}
