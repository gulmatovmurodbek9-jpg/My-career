-- Тарҷумаи мазмуни ихтисосҳо ба русӣ ва англисӣ.
--
-- Як сутуни jsonb, на ҷадвали алоҳида: ҳама майдонҳои тарҷумашаванда якҷо
-- хонда мешаванд ва ҳеҷ join лозим намешавад — саҳифаи ихтисос аллакай як
-- дархост аст ва бояд ҳамон тавр монад.
--
-- Сохтор:
--   {"ru": {"name": "...", "description": "...", "roadmap": [...]},
--    "en": {...}}
--
-- `code` ҳеҷ гоҳ ин ҷо намеояд: он шиносаи расмии ММТ аст ва дар ҳама
-- забон як хел мемонад.
ALTER TABLE career ADD COLUMN IF NOT EXISTS translations jsonb NOT NULL DEFAULT '{}'::jsonb;

-- Скрипти тарҷума аз рӯи ҳамин филтр сатрҳои коркарднашударо мегирад,
-- то пас аз қатъ шудан аз ҷои худ давом кунад.
CREATE INDEX IF NOT EXISTS idx_career_translations_empty
    ON career ((translations = '{}'::jsonb));
